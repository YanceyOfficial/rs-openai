#[allow(unused)]
use crate::apis;
use crate::shared::types::Stop;
use bon::Builder;
use serde::{Deserialize, Serialize};
use std::collections::HashMap;

#[derive(Debug, Serialize, Deserialize, Clone, Default, strum::Display)]
#[serde(rename_all = "lowercase")]
pub enum Role {
    #[strum(serialize = "system")]
    System,
    #[default]
    #[strum(serialize = "user")]
    User,
    #[strum(serialize = "assistant")]
    Assistant,
    #[strum(serialize = "tool")]
    Tool,
}

#[derive(Builder, Debug, Clone, Deserialize, Serialize)]
pub struct ChatCompletionMessage {
    /// The role of the author of this message. One of `system`, `user`, `assistant`, or `tool`.
    pub role: Role,

    /// The contents of the message. `None` (serializes as `null`) when an assistant message
    /// contains only tool calls — real OpenAI responses do this.
    #[builder(into)]
    pub content: Option<String>,

    /// The name of the author of this message. May contain a-z, A-Z, 0-9, and underscores, with a maximum length of 64 characters.
    #[builder(into)]
    pub name: Option<String>,

    /// Populated on assistant messages that call one or more tools instead of (or alongside)
    /// producing text.
    pub tool_calls: Option<Vec<ToolCall>>,

    /// Set on `role: Tool` messages to link this message's `content` (the tool's result) back
    /// to the `ToolCall.id` it answers.
    #[builder(into)]
    pub tool_call_id: Option<String>,

    /// The refusal message generated by the model, if it declined to comply with the request.
    pub refusal: Option<String>,
}

/// A single function call requested by the model, as part of an assistant message's
/// `tool_calls`.
#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct FunctionCall {
    pub name: String,

    /// Raw JSON-encoded arguments, deliberately left unparsed — decide how (and whether) to
    /// validate/deserialize this against your own tool's parameter schema.
    pub arguments: String,
}

/// One tool call the model made, inside an assistant message's `tool_calls` array.
#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct ToolCall {
    pub id: String,

    /// Always `"function"` as of this writing; OpenAI has never shipped a second tool-call type.
    #[serde(rename = "type")]
    pub kind: String,

    pub function: FunctionCall,
}

/// A single, possibly-partial function-call fragment from a streaming delta. Unlike the
/// non-streaming `FunctionCall`, `name` is optional and `arguments` defaults to empty —
/// OpenAI only sends `name` on the first chunk for a given tool call, and streams
/// `arguments` token-by-token across many chunks.
#[derive(Debug, Serialize, Deserialize, Clone, Default)]
pub struct FunctionCallChunk {
    pub name: Option<String>,
    #[serde(default)]
    pub arguments: String,
}

/// One partial tool-call fragment inside a streaming `Delta`. `index` correlates fragments
/// across chunks when multiple tool calls stream in parallel (always present). `id`/`kind`
/// are only present on the first chunk for a given `index`.
#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct ToolCallChunk {
    pub index: u32,
    pub id: Option<String>,
    #[serde(rename = "type")]
    pub kind: Option<String>,
    pub function: Option<FunctionCallChunk>,
}

/// A function's definition, as advertised to the model via `CreateChatRequest.tools`.
#[derive(Builder, Debug, Serialize, Deserialize, Clone)]
pub struct FunctionDefinition {
    #[builder(into)]
    pub name: String,

    #[builder(into)]
    #[serde(skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,

    /// A JSON Schema object describing the function's parameters.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub parameters: Option<serde_json::Value>,

    #[serde(skip_serializing_if = "Option::is_none")]
    pub strict: Option<bool>,
}

/// A tool the model may call, as an entry in `CreateChatRequest.tools`.
#[derive(Builder, Debug, Serialize, Deserialize, Clone)]
pub struct ChatCompletionTool {
    /// Always `"function"` as of this writing.
    #[serde(rename = "type")]
    #[builder(default = "function".to_string())]
    pub kind: String,

    pub function: FunctionDefinition,
}

/// The plain string modes `tool_choice` can take.
#[derive(Debug, Serialize, Deserialize, Clone)]
#[serde(rename_all = "lowercase")]
pub enum ToolChoiceMode {
    None,
    Auto,
    Required,
}

#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct ToolChoiceFunctionName {
    pub name: String,
}

/// Controls which (if any) tool the model calls. Either a plain mode string
/// (`"none"`/`"auto"`/`"required"`) or an object forcing one specific function.
#[derive(Debug, Serialize, Deserialize, Clone)]
#[serde(untagged)]
pub enum ToolChoice {
    Mode(ToolChoiceMode),
    Specific {
        #[serde(rename = "type")]
        kind: String,
        function: ToolChoiceFunctionName,
    },
}

#[derive(Builder, Debug, Serialize, Deserialize, Clone)]
pub struct JsonSchemaFormat {
    #[builder(into)]
    pub name: String,
    #[builder(into)]
    #[serde(skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,
    pub schema: serde_json::Value,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub strict: Option<bool>,
}

/// Structured-output controls. `Text`/`JsonObject` are unit variants (serialize as
/// `{"type": "text"}`/`{"type": "json_object"}` — internally-tagged enums support unit
/// variants this way); `JsonSchema` carries the actual schema.
#[derive(Debug, Serialize, Deserialize, Clone)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ChatResponseFormat {
    Text,
    JsonObject,
    JsonSchema { json_schema: JsonSchemaFormat },
}

#[derive(Debug, Serialize, Deserialize, Clone)]
#[serde(rename_all = "snake_case")]
pub enum ChatReasoningEffort {
    None,
    Minimal,
    Low,
    Medium,
    High,
    Xhigh,
    Max,
}

#[derive(Debug, Serialize, Deserialize, Clone)]
#[serde(rename_all = "snake_case")]
pub enum ServiceTier {
    Auto,
    Default,
    Flex,
    Scale,
    Priority,
    Fast,
}

#[derive(Builder, Clone, Debug, Serialize)]
pub struct CreateChatRequest {
    /// ID of the model to use.
    /// See the [model endpoint compatibility](https://platform.openai.com/docs/models/model-endpoint-compatibility) table for details on which models work with the Chat API.
    #[builder(into)]
    pub model: String,

    /// A list of messages describing the conversation so far.
    pub messages: Vec<ChatCompletionMessage>,

    /// What sampling temperature to use, between 0 and 2.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub temperature: Option<f32>, // min: 0, max: 2, default: 1

    /// An alternative to sampling with temperature, called nucleus sampling.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub top_p: Option<f32>, //  default: 1

    /// How many chat completion choices to generate for each input message.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub n: Option<u8>, // default: 1

    /// If set, partial message deltas will be sent, like in ChatGPT.
    /// For streamed progress, use [`create_with_stream`](apis::chat::Chat::create_with_stream).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub stream: Option<bool>, // default: false

    /// Up to 4 sequences where the API will stop generating further tokens.
    #[builder(into)]
    #[serde(skip_serializing_if = "Option::is_none")]
    pub stop: Option<Stop>, // default: null

    /// The maximum number of tokens to generate in the chat completion.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub max_tokens: Option<u32>,

    /// Number between -2.0 and 2.0. Positive values penalize new tokens based on whether they appear in the text so far.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub presence_penalty: Option<f32>, // min: -2.0, max: 2.0, default: 0

    /// Number between -2.0 and 2.0. Positive values penalize new tokens based on their existing frequency in the text so far.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub frequency_penalty: Option<f32>, // min: -2.0, max: 2.0, default: 0

    /// Modify the likelihood of specified tokens appearing in the completion.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub logit_bias: Option<HashMap<String, serde_json::Value>>, // default: null

    /// A unique identifier representing your end-user, which can help OpenAI to monitor and detect abuse.
    #[builder(into)]
    #[serde(skip_serializing_if = "Option::is_none")]
    pub user: Option<String>,

    /// A list of tools the model may call.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tools: Option<Vec<ChatCompletionTool>>,

    /// Controls which (if any) tool is called by the model.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tool_choice: Option<ToolChoice>,

    /// Whether to enable parallel function calling during tool use.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub parallel_tool_calls: Option<bool>,

    #[serde(skip_serializing_if = "Option::is_none")]
    pub response_format: Option<ChatResponseFormat>,

    #[serde(skip_serializing_if = "Option::is_none")]
    pub reasoning_effort: Option<ChatReasoningEffort>,

    #[serde(skip_serializing_if = "Option::is_none")]
    pub service_tier: Option<ServiceTier>,

    #[serde(skip_serializing_if = "Option::is_none")]
    pub stream_options: Option<crate::shared::types::StreamOptions>,

    #[serde(skip_serializing_if = "Option::is_none")]
    pub seed: Option<i64>,

    #[serde(skip_serializing_if = "Option::is_none")]
    pub logprobs: Option<bool>,

    /// 0-20. Requires `logprobs: true`.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub top_logprobs: Option<u8>,

    /// Persist this completion for later retrieval via `Chat::retrieve`/`list`/`delete`.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub store: Option<bool>,

    #[serde(skip_serializing_if = "Option::is_none")]
    pub metadata: Option<HashMap<String, String>>,

    /// Newer, reasoning-model-compatible replacement for `max_tokens`. `max_tokens` stays
    /// supported — no removal.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub max_completion_tokens: Option<u32>,

    /// Newer, privacy-friendlier replacement for `user`. `user` stays supported.
    #[builder(into)]
    #[serde(skip_serializing_if = "Option::is_none")]
    pub safety_identifier: Option<String>,

    #[builder(into)]
    #[serde(skip_serializing_if = "Option::is_none")]
    pub prompt_cache_key: Option<String>,
}

#[derive(Debug, Deserialize, Clone, Serialize)]
pub struct Message {
    pub role: String,
    pub content: String,
}

#[derive(Debug, Deserialize, Clone, Serialize)]
pub struct ChatUsage {
    pub prompt_tokens: u32,
    pub completion_tokens: u32,
    pub total_tokens: u32,
    pub completion_tokens_details: Option<CompletionTokensDetails>,
    pub prompt_tokens_details: Option<PromptTokensDetails>,
}

#[derive(Debug, Deserialize, Clone, Serialize)]
pub struct CompletionTokensDetails {
    pub reasoning_tokens: u32,
    pub audio_tokens: u32,
    pub accepted_prediction_tokens: u32,
    pub rejected_prediction_tokens: u32,
}

#[derive(Debug, Deserialize, Clone, Serialize)]
pub struct PromptTokensDetails {
    pub audio_tokens: u32,
    pub cached_tokens: u32,
    pub cache_write_tokens: u32,
}

#[derive(Debug, Deserialize, Clone, Serialize)]
pub struct ChatChoice {
    pub message: ChatCompletionMessage,
    pub finish_reason: String,
    pub index: u32,
}

#[derive(Debug, Deserialize, Clone, Serialize)]
pub struct ChatResponse {
    pub id: String,
    pub object: String,
    pub created: u32,
    pub choices: Vec<ChatChoice>,
    pub usage: ChatUsage,
}

#[derive(Debug, Deserialize, Clone, Serialize)]
pub struct Delta {
    pub content: Option<String>,
    pub tool_calls: Option<Vec<ToolCallChunk>>,
}

#[derive(Debug, Deserialize, Clone, Serialize)]
pub struct ChatChoiceStream {
    pub delta: Delta,
    pub finish_reason: Option<String>,
    pub index: u32,
}

#[derive(Debug, Deserialize, Clone, Serialize)]
pub struct ChatStreamResponse {
    pub id: String,
    pub object: String,
    pub model: String,
    pub created: u32,
    pub choices: Vec<ChatChoiceStream>,
}
